<?php

return [

    /*
    |--------------------------------------------------------------------------
    | Лимиты вложений
    |--------------------------------------------------------------------------
    | Все размеры в байтах. На проде задаются через .env.
    */

    // Максимальный размер одного файла (по умолчанию 10 ГБ). Грузится чанками,
    // поэтому в один HTTP-запрос целиком НЕ влезает — см. chunk_bytes.
    'max_bytes' => (int) env('UPLOAD_MAX_BYTES', 10 * 1024 * 1024 * 1024),

    // Файлы НЕ больше этого порога шифруются на диске (шифрование идёт целиком в
    // памяти). Всё, что крупнее, хранится как есть и отдаётся потоком с поддержкой
    // перемотки (Range). По умолчанию 25 МБ — как старый лимит вложений.
    'encrypt_max_bytes' => (int) env('UPLOAD_ENCRYPT_MAX_BYTES', 25 * 1024 * 1024),

    // Рекомендуемый размер чанка для клиента (один HTTP-запрос на загрузке).
    // Должен укладываться в post_max_size/client_max_body_size с запасом.
    'chunk_bytes' => (int) env('UPLOAD_CHUNK_BYTES', 16 * 1024 * 1024),

    // Персональная квота на пользователя (сумма размеров его вложений).
    // При превышении init вернёт 413. По умолчанию 20 ГБ.
    'user_quota_bytes' => (int) env('UPLOAD_USER_QUOTA_BYTES', 20 * 1024 * 1024 * 1024),

    // Сколько свободного места на диске держим как неприкосновенный запас.
    // Если после приёма файла останется меньше — вытесняем самые старые вложения
    // (LRU по last_accessed_at). По умолчанию 5 ГБ.
    'min_free_bytes' => (int) env('UPLOAD_MIN_FREE_BYTES', 5 * 1024 * 1024 * 1024),

    // Срок хранения истории: сообщения и их файлы старше N дней удаляются кроном
    // attachments:prune. 0 — ретеншн выключен.
    'retention_days' => (int) env('UPLOAD_RETENTION_DAYS', 30),

    // Через сколько часов брошенная (недокачанная) сессия загрузки и её временный
    // файл удаляются.
    'session_ttl_hours' => (int) env('UPLOAD_SESSION_TTL_HOURS', 24),
];
